if __name__ == "__main__":

    from src.mesh.mesh import create_mesh
    from src.graph.graph import create_graph

    print("=" * 70)
    print("GRAPH FEATURES MODULE TEST")
    print("=" * 70)

    # ---------------------------------------------------------
    # Create reference mesh
    # ---------------------------------------------------------

    mesh = create_mesh(
        width=1.0,
        height=1.0,
        nx=5,
        ny=5
    )

    # ---------------------------------------------------------
    # Create graph
    # ---------------------------------------------------------

    graph = create_graph(mesh)

    # ---------------------------------------------------------
    # Reference configuration
    # ---------------------------------------------------------

    X = graph.nodes.copy()

    # ---------------------------------------------------------
    # Create a simple deformation
    #
    # x = F X
    #
    # F =
    #
    # [1.1  0.1]
    # [0.0  0.9]
    #
    # ---------------------------------------------------------

    F = np.array([
        [1.1, 0.1],
        [0.0, 0.9]
    ])

    x = (F @ X.T).T

    # ---------------------------------------------------------
    # Create features
    # ---------------------------------------------------------

    features = create_features(
        graph,
        reference_nodes=X,
        current_nodes=x
    )

    # =========================================================
    # OUTPUT
    # =========================================================

    print("\nNumber of nodes:")
    print(features.n_nodes)

    print("\nNode feature dimension:")
    print(features.n_node_features)

    print("\nNumber of edges:")
    print(features.n_edges)

    print("\nEdge feature dimension:")
    print(features.n_edge_features)

    print("\nFirst node features:")
    print(features.node_features[:5])

    print("\nFirst edge features:")
    print(features.edge_features[:5])

    # =========================================================
    # CHECKS
    # =========================================================

    expected_node_dimension = 6
    expected_edge_dimension = 6

    node_dimension_ok = (
        features.n_node_features
        ==
        expected_node_dimension
    )

    edge_dimension_ok = (
        features.n_edge_features
        ==
        expected_edge_dimension
    )

    # ---------------------------------------------------------
    # Check displacement
    # ---------------------------------------------------------

    expected_displacement = x - X

    computed_displacement = (
        features.node_features[:, 4:6]
    )

    displacement_error = np.max(
        np.abs(
            computed_displacement
            -
            expected_displacement
        )
    )

    # ---------------------------------------------------------
    # Check reference edge length
    # ---------------------------------------------------------

    first_sender = graph.senders[0]
    first_receiver = graph.receivers[0]

    expected_dX = (
        X[first_receiver]
        -
        X[first_sender]
    )

    expected_L0 = np.linalg.norm(
        expected_dX
    )

    first_edge = features.edge_features[0]

    edge_reference_error = np.max(
        np.abs(
            first_edge[:2]
            -
            expected_dX
        )
    )

    edge_length_error = abs(
        first_edge[2]
        -
        expected_L0
    )

    # =========================================================
    # RESULTS
    # =========================================================

    print("\n" + "-" * 70)
    print("CHECKS")
    print("-" * 70)

    print(
        "\nNode feature dimension:",
        "PASS" if node_dimension_ok else "FAIL"
    )

    print(
        "Edge feature dimension:",
        "PASS" if edge_dimension_ok else "FAIL"
    )

    print(
        "Displacement computation:",
        "PASS" if displacement_error < 1e-12
        else "FAIL"
    )

    print(
        "Reference edge vector:",
        "PASS" if edge_reference_error < 1e-12
        else "FAIL"
    )

    print(
        "Reference edge length:",
        "PASS" if edge_length_error < 1e-12
        else "FAIL"
    )

    # ---------------------------------------------------------
    # Final result
    # ---------------------------------------------------------

    all_passed = (
        node_dimension_ok
        and edge_dimension_ok
        and displacement_error < 1e-12
        and edge_reference_error < 1e-12
        and edge_length_error < 1e-12
    )

    print("\n" + "=" * 70)

    if all_passed:
        print("RESULT: PASS")
    else:
        print("RESULT: FAIL")